def make_record(index, hall, group, entry, prefix):
    title, contributor, age, note = entry
    source_name, source_url = group["source"]
    is_topic = bool(group.get("isTopic"))
    is_asset = bool(group.get("isAsset"))
    # 权利状态：未逐条完成证据归档前，一律不标 verified。
    rights = "unknown" if is_topic or is_asset else "pending"
    return {
        "id": f"{prefix}-{index:03d}",
        "hall": hall,
        "group": group["id"],
        "groupName": group["name"],
        "title": title,
        "origin": "选题方向" if is_topic else ("版本 / 资产层" if is_asset else contributor.split(" · ")[-1] if " · " in contributor else "中国 / 世界传统"),
        "contributor": contributor,
        "ageBand": age,
        "note": note,
        "sourceName": source_name,
        "sourceUrl": source_url,
        "researchStatus": "discovered",
        "rightsStatus": rights,
        "qualityStatus": "unreviewed",
        "accessMethod": "none" if is_topic else "source_link",
        "publicationStatus": "draft",
        "isTopic": is_topic,
        "isAsset": is_asset,
        "assetNote": (
            "仅登记作品身份、来源线索与待核验事项；不保存正文、译文、插画、音视频。"
            if not is_asset
            else "此条为内容版本 / 媒体资产类型线索，不是独立作品；按 DATA_MODEL 与作品主记录分开建档。"
        ),
    }


def build():
    records = []
    for hall, groups, entries, prefix in (
        ("story", STORY_GROUPS, STORY_ENTRIES, "ST"),
        ("poetry", POETRY_GROUPS, POETRY_ENTRIES, "PO"),
    ):
        counter = 0
        for group in groups:
            items = entries[group["id"]]
            if len(items) != group["target"]:
                raise ValueError(f"{group['id']}: expected {group['target']} entries, got {len(items)}")
            for item in items:
                counter += 1
                records.append(make_record(counter, hall, group, item, prefix))

    stats = {}
    for hall in ("story", "poetry"):
        rows = [r for r in records if r["hall"] == hall]
        stats[hall] = {
            "total": len(rows),
            "topics": sum(1 for r in rows if r["isTopic"]),
            "assets": sum(1 for r in rows if r["isAsset"]),
            "works": sum(1 for r in rows if not r["isTopic"] and not r["isAsset"]),
            "groups": len([g for g in STORY_GROUPS + POETRY_GROUPS if g["hall"] == hall]),
        }

    payload = {
        "version": "0.1",
        "generatedOn": date.today().isoformat(),
        "basis": [
            "docs/PROJECT_PRINCIPLES.md v1.0（GitHub main，SHA f60cbb0931d196f098459c8eef6774ee8150d2f6）",
            "docs/DATA_MODEL.md v0.1 §4（GitHub main，SHA 1d3fb104478369606169b06165f162622a47fccc）",
            "docs/STORY_LIBRARY_PLAN_V1.md §2 / §9",
        ],
        "rule": "先研究采集，再判断使用；版权未知不作为排除研究候选的理由；未逐条完成权利证据归档前不标 verified。",
        "statusModel": STATUS_MODEL,
        "statusLabels": STATUS_LABELS,
        "groups": [g for g in STORY_GROUPS + POETRY_GROUPS],
        "records": records,
        "stats": stats,
    }
    OUT.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return payload


